package com.company;

public class ForLoopCheckEvenAndOdd {
     public static void main(String[] args) {
         int even=5;
         for (int i = 0; i <even; i++) {
             System.out.println(i++);
         }
         int  odd=10;
         for (int i = 0; i<odd ; i++) {
             System.out.println(2*i+1);

         }
    }
}
